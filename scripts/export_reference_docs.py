#!/usr/bin/env python
"""Regenerate the per-domain reference documentation shipped in reference/.

Everything under reference/ is derived from env/domains/*/ and is regenerated by
this script, so it can never drift from the code that actually runs. For each of
the seven domains it writes:

  reference/prompts/<domain>_system_prompt.md   the system prompt the agent receives
  reference/schemas/<domain>_tools.json         the tool (function-calling) schemas
  reference/domains/<domain>.md                 functions, constraints, and the
                                                helper functions that verify them

The paper's appendix works one domain (bank) through in full; the tables here
cover all seven.

Usage:  python scripts/export_reference_docs.py
"""

import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from env.task import task_default_dep_full, task_initializer          # noqa: E402
from env.variables import domain_assistant_keys                       # noqa: E402
from env.helpers import get_action_full_description                   # noqa: E402

DOMAINS = ['bank', 'dmv', 'healthcare', 'library', 'online_market', 'hotel', 'university']
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, 'reference')

# the defaults run_simulation.py uses for the main results
CONSTRAINT_OPTION = 'full'
DESCR_FORMAT = 'structured'
ENV_MODE = 'prompt'


def first_task(domain):
    with open(os.path.join(ROOT, 'data', '%s_tasks.json' % domain)) as f:
        tasks = json.load(f)
    # the file is keyed by service function; that key is the task's user_goal
    for goal, group in tasks.items():
        if group:
            task = dict(group[0])
            task.setdefault('user_goal', goal)
            return task
    raise RuntimeError('no tasks for %s' % domain)


def assistant_info(domain):
    dep_innate_full, default_dep_full, default_dep_full_descr = task_default_dep_full(
        domain, CONSTRAINT_OPTION, DESCR_FORMAT, dependency_verb_dep_orig=True)
    _, _, info, _ = task_initializer(
        domain, first_task(domain), dep_innate_full, default_dep_full,
        default_dep_full_descr, None, ENV_MODE, False, DESCR_FORMAT)
    return info


def fmt_dep(dep):
    """Render a constraint composition tuple as a readable boolean expression."""
    if not dep:
        return 'None'
    kind = dep[0]
    if kind == 'single':
        return dep[1]
    if kind in ('and', 'or'):
        return (' %s ' % kind.upper()).join('(%s)' % fmt_dep(d) if d and d[0] in ('and', 'or')
                                            else fmt_dep(d) for d in dep[1])
    if kind in ('chain', 'gate'):
        return ' THEN '.join(fmt_dep(d) for d in dep[1])
    return str(dep)


def md_table(headers, rows):
    out = ['| ' + ' | '.join(headers) + ' |',
           '|' + '|'.join('---' for _ in headers) + '|']
    for r in rows:
        out.append('| ' + ' | '.join(str(c).replace('|', '\\|').replace('\n', ' ') for c in r) + ' |')
    return '\n'.join(out)


def domain_markdown(domain):
    a = domain_assistant_keys[domain]
    deps = getattr(a, 'action_required_dependencies', {})
    service, helper = [], []
    for name in sorted(a.action_descriptions):
        desc = get_action_full_description(a.action_descriptions, a.action_returns, name)
        row = ['`%s`' % name, desc, '`%s`' % fmt_dep(deps.get(name))]
        (helper if name.startswith('internal_') else service).append(row)

    cdesc = dict(getattr(a, 'positive_constraint_descriptions', {}))
    links = getattr(a, 'constraint_links', {})
    crows = []
    for c in sorted(cdesc):
        verifiers = links.get(c)
        if isinstance(verifiers, (list, tuple, set)):
            v = ', '.join('`%s`' % x for x in verifiers) or 'None'
        elif verifiers:
            v = '`%s`' % verifiers
        else:
            v = 'None'
        crows.append(['`%s`' % c, cdesc[c], v])

    title = domain.replace('_', ' ').title()
    return '\n\n'.join([
        '# %s domain' % title,
        '<!-- generated by scripts/export_reference_docs.py -- do not edit by hand -->',
        '## Service functions',
        md_table(['Function', 'Description', 'Constraint composition'], service),
        '## Helper functions',
        md_table(['Function', 'Description', 'Constraint composition'], helper),
        '## Constraints',
        md_table(['Constraint', 'Description', 'Helper functions'], crows),
        ''])


def main():
    for sub in ('prompts', 'schemas', 'domains'):
        os.makedirs(os.path.join(OUT, sub), exist_ok=True)
    for domain in DOMAINS:
        info = assistant_info(domain)
        with open(os.path.join(OUT, 'prompts', '%s_system_prompt.md' % domain), 'w') as f:
            f.write(info['instructions'].rstrip() + '\n')
        with open(os.path.join(OUT, 'schemas', '%s_tools.json' % domain), 'w') as f:
            json.dump(info['tools'], f, indent=2)
            f.write('\n')
        with open(os.path.join(OUT, 'domains', '%s.md' % domain), 'w') as f:
            f.write(domain_markdown(domain))
        print('%-14s prompt %5d chars | %2d tools | tables written'
              % (domain, len(info['instructions']), len(info['tools'])))


if __name__ == '__main__':
    main()
